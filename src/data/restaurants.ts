export function getRestaurant(id: string): Restaurant | undefined {
  return restaurants.find((r) => r.id === id)
}

const NEW_WITHIN_DAYS = 90
const HOT_WEEKLY_RESERVATIONS = 50

export function isNewRestaurant(restaurant: Restaurant, now: Date = new Date()): boolean {
  const opened = new Date(restaurant.openedAt).getTime()
  const diffDays = (now.getTime() - opened) / (1000 * 60 * 60 * 24)
  return diffDays >= 0 && diffDays <= NEW_WITHIN_DAYS
}

export function isHotRestaurant(restaurant: Restaurant): boolean {
  return restaurant.weeklyReservations >= HOT_WEEKLY_RESERVATIONS
}
